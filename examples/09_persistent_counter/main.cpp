/**
 * Two units use one executor registration and retain independent counter values.
 * The caller queues four increments; the controller appends two more after execution
 * begins. The final counts are A = 9 and B = 7.
 */

#include <cstdint>
#include <exception>
#include <iostream>
#include <memory>
#include <span>
#include <utility>

#include "miaow.hpp"
#include "miaow_io.hpp"
#include "../config.hpp"

// Each executor owns a counter that survives successive operations
class CounterTaskExecutor : public miaow::TaskExecutor {
  public:
    caf::result<miaow::TaskResult> execute(const miaow::Task& task) override {
        if (task.operation_ != "increment") {
            return miaow::make_failed_task_result("unknown counter operation");
        }
        count_ += caf::get<std::int64_t>(task.args_.at(0));
        return miaow::TaskResult{miaow::TaskStatus::succeeded, "incremented",
                                 caf::config_value{count_}};
    }

  private:
    std::int64_t count_{0};
};

// Generate the last two operations using handles retained across job submission
class CounterController : public miaow::JobController {
  public:
    CounterController(miaow::SimulationUnitHandle a, miaow::SimulationUnitHandle b)
        : a_(a), b_(b) {}

    // The first completion queues the final increments and requests unit removal.
    // Later completions need no new work; unit loss fails the job.
    void callback(miaow::Job& job, std::span<const miaow::TaskRecord>,
                  std::span<const miaow::UnitFailure> failed_units) override {
        // Fail the job if a unit becomes unavailable
        if (!failed_units.empty()) {
            job.fail(failed_units.front().reason_);
            return;
        }
        if (generated_) {
            return;
        }
        generated_ = true;
        job.add_task(a_, "increment", 4);
        job.add_task(b_, "increment", 2);

        // Close both units; all accepted increments finish before resource release
        job.remove_unit(a_);
        job.remove_unit(b_);
    }

  private:
    miaow::SimulationUnitHandle a_;
    miaow::SimulationUnitHandle b_;
    bool generated_{false};
};

int main(int argc, char* argv[]) {
    try {
        // Read runtime settings; this example uses a fixed sequence of increments
        miaow::RuntimeOptions runtime_options;
        read_example_config(argc, argv, runtime_options);

        // One registration supplies the implementation for both independent units
        miaow::TaskExecutorRegistry registry;
        const miaow::TaskExecutorId counter = registry.add<CounterTaskExecutor>();
        miaow::Runtime runtime(registry, runtime_options);

        // Each SimulationUnit owns its own executor instance
        miaow::Job job;
        const miaow::SimulationUnitHandle a = job.add_unit("A", counter);
        const miaow::SimulationUnitHandle b = job.add_unit("B", counter);

        // Queue initial operations; each unit processes its own tasks in order
        job.add_task(a, "increment", 2);
        job.add_task(a, "increment", 3);
        job.add_task(b, "increment", 1);
        job.add_task(b, "increment", 4);

        // Continue the same units from the first completion callback
        job.set_controller(std::make_unique<CounterController>(a, b));

        // Submit the job
        miaow::JobHandle job_handle = runtime.submit_job(std::move(job));

        // Wait for completion and retrieve the job record
        const miaow::JobRecord record = job_handle.get();

        // Report all six operations, including those generated by the controller
        miaow::print_job_summary(record);
        return miaow::all_tasks_succeeded(record) ? 0 : 1;
    } catch (const std::exception& exception) {
        std::cerr << exception.what() << '\n';
        return 1;
    }
}
